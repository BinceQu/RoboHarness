def _public_bddl_completion(goals: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    goals = goals if isinstance(goals, dict) else {}
    conditions = []
    for fallback_index, item in enumerate(goals.get("items") or []):
        if not isinstance(item, dict):
            continue
        condition = str(item.get("full") or item.get("label") or "").strip()
        conditions.append({
            "index": int(item.get("index", fallback_index)),
            "condition": condition,
            "satisfied": bool(item.get("satisfied", False)),
        })
    satisfied = sum(1 for item in conditions if item["satisfied"])
    total = len(conditions)
    if not conditions:
        try:
            satisfied = max(0, int(goals.get("satisfied", 0)))
        except (TypeError, ValueError):
            satisfied = 0
        try:
            total = max(0, int(goals.get("total", 0)))
        except (TypeError, ValueError):
            total = 0
        satisfied = min(satisfied, total)
    return {
        "complete": bool(goals.get("complete", False)),
        "satisfied": satisfied,
        "total": total,
        "conditions": conditions,
    }


def build_task_goals_only_memory(
    *,
    task_name: str = "",
    task_instruction: str = "",
    goals: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """Build memory with no simulator-derived object or robot geometry."""
    instruction = str(task_instruction or _task_instruction(task_name)).strip()
    return {
        "task_instruction": instruction,
        "bddl_completion": _public_bddl_completion(goals),
    }


def format_task_goals_only_memory(mem: Dict[str, Any]) -> str:
    instruction = str(mem.get("task_instruction") or "").strip()
    bddl = mem.get("bddl_completion")
    bddl = bddl if isinstance(bddl, dict) else _public_bddl_completion(None)
    satisfied = int(bddl.get("satisfied", 0) or 0)
    total = int(bddl.get("total", 0) or 0)
    lines = [
        "Task instruction:",
        instruction,
        "",
        "BDDL completion:",
        f"complete: {str(bool(bddl.get('complete', False))).lower()}",
        f"satisfied: {satisfied}/{total}",
    ]
    for item in bddl.get("conditions") or []:
        if not isinstance(item, dict):
            continue
        mark = "x" if item.get("satisfied") else " "
        condition = str(item.get("condition") or "").strip()
        lines.append(f"- [{mark}] {condition}")
    return "\n".join(lines).rstrip()


def sanitize_model_payload(
    payload: Any,
    *,
    task_name: str,
    goals: Optional[Dict[str, Any]],
) -> Any:
    """Remove privileged task geometry from a model-visible API payload."""
    public_memory = build_task_goals_only_memory(task_name=task_name, goals=goals)
    public_text = format_task_goals_only_memory(public_memory)

    def _sanitize(value: Any) -> Any:
        if isinstance(value, dict):
            clean: Dict[str, Any] = {}
            for key, child in value.items():
                if key == "memory":
                    clean[key] = dict(public_memory)
                elif key == "memory_text":
                    clean[key] = public_text
                elif key == "tro":
                    clean[key] = {}
                else:
                    clean[key] = _sanitize(child)
            return clean
        if isinstance(value, list):
            return [_sanitize(child) for child in value]
        if isinstance(value, tuple):
            return tuple(_sanitize(child) for child in value)
        return value

    return _sanitize(payload)


def _round_float(v: Any, ndigits: int = 4) -> Optional[float]:
    try:
        f = float(v)
    except Exception:
        return None
    if not math.isfinite(f):
        return None
    return round(f, ndigits)


def _norm_angle_deg(deg: Any) -> Optional[float]:
    try:
        f = float(deg)
    except Exception:
        return None
    if not math.isfinite(f):
        return None
    return (f + 180.0) % 360.0 - 180.0


def _direction_from_spin_deg(spin_deg: Optional[float]) -> str:
    if spin_deg is None or not math.isfinite(float(spin_deg)):
        return "unknown"
    spin = float(spin_deg)
    a = abs(spin)
    if a <= 12.0:
        return "front"
    if a >= 168.0:
        return "back"
    side = "left" if spin > 0.0 else "right"
    if a < 60.0:
        return f"front-{side}"
    if a <= 120.0:
        return side
    return f"back-{side}"


def _numeric_robot_pose(world: Any, robot_pose: Dict[str, Any]) -> Tuple[Dict[str, float], str]:
    pose = dict(robot_pose or {})
    source = "server_cache"

    def num(key: str) -> Optional[float]:
        try:
            val = float(pose.get(key))
        except Exception:
            return None
        return val if math.isfinite(val) else None

    if num("x") is None or num("y") is None or num("z") is None or num("yaw_deg") is None:
        try:
            wp = world.robot_pose()
            pose = {
                "x": float(wp.pos[0]),
                "y": float(wp.pos[1]),
                "z": float(wp.pos[2]),
                "yaw_deg": math.degrees(float(wp.yaw)),
            }
            source = "world.robot_pose"
        except Exception:
            pose = {
                "x": float(num("x") or 0.0),
                "y": float(num("y") or 0.0),
                "z": float(num("z") or 0.0),
                "yaw_deg": float(num("yaw_deg") or 0.0),
            }
            source = "fallback_zero"
    return {
        "x": float(pose.get("x", 0.0)),
        "y": float(pose.get("y", 0.0)),
        "z": float(pose.get("z", 0.0)),
        "yaw_deg": float(pose.get("yaw_deg", 0.0)),
    }, source


def _pitch_hint_for_center(
    center: np.ndarray,
    cam: Optional[Dict[str, Any]],
) -> Dict[str, Any]:
    """Return a q3/adjust_pitch hint to vertically center an object.

    Convention matches /api/v2/adjust_pitch: positive degree means look up
    (increase head/camera elevation), negative means look down.  The estimate
    compares the target elevation from the current head camera position against
    the current head optical-axis elevation.  It is independent of yaw, so it
    remains meaningful together with spin_to_view for off-screen objects.
    """
    if not isinstance(cam, dict) or cam.get("pos") is None or cam.get("quat") is None:
        return {
            "pitch_to_view_deg": None,
            "target_pitch_deg": None,
            "camera_pitch_deg": None,
            "pitch_hint_reason": "no_head_camera_pose",
        }
    try:
        cam_pos = np.asarray(cam.get("pos"), dtype=np.float64).reshape(3)
        cam_quat = np.asarray(cam.get("quat"), dtype=np.float64).reshape(4)
        target = np.asarray(center, dtype=np.float64).reshape(3)
        if not (np.all(np.isfinite(cam_pos)) and np.all(np.isfinite(cam_quat)) and np.all(np.isfinite(target))):
            raise ValueError("non_finite_pose_or_target")
        delta = target - cam_pos
        horiz = math.hypot(float(delta[0]), float(delta[1]))
        if horiz < 1e-5:
            target_pitch = 90.0 if float(delta[2]) >= 0.0 else -90.0
        else:
            target_pitch = math.degrees(math.atan2(float(delta[2]), horiz))
        R = _quat_to_mat(cam_quat)
        optical_world = R @ np.array([0.0, 0.0, -1.0], dtype=np.float64)
        optical_h = math.hypot(float(optical_world[0]), float(optical_world[1]))
        if optical_h < 1e-8:
            camera_pitch = 90.0 if float(optical_world[2]) >= 0.0 else -90.0
        else:
            camera_pitch = math.degrees(math.atan2(float(optical_world[2]), optical_h))
        pitch_delta = _norm_angle_deg(float(target_pitch) - float(camera_pitch))
        # adjust_pitch endpoint rejects |degree| > 45; expose the raw estimate
        # and a safe command-sized value separately.
        pitch_cmd = max(-45.0, min(45.0, float(pitch_delta)))
        return {
            "pitch_to_view_deg": _round_float(pitch_cmd, 1),
            "pitch_to_view_raw_deg": _round_float(pitch_delta, 1),
            "target_pitch_deg": _round_float(target_pitch, 1),
            "camera_pitch_deg": _round_float(camera_pitch, 1),
            "pitch_hint_reason": "target_elevation_minus_camera_elevation",
            "pitch_sign": "positive means look up / adjust_pitch(degree>0); negative means look down",
        }
    except Exception as exc:
        return {
            "pitch_to_view_deg": None,
            "target_pitch_deg": None,
            "camera_pitch_deg": None,
            "pitch_hint_reason": str(exc),
        }


def _spin_hint_for_center(
    center: np.ndarray,
    robot_pos: np.ndarray,
    robot_yaw_deg: float,
) -> Dict[str, Any]:
    center = np.asarray(center, dtype=np.float64).reshape(3)
    robot_pos = np.asarray(robot_pos, dtype=np.float64).reshape(3)
    dx = float(center[0] - robot_pos[0])
    dy = float(center[1] - robot_pos[1])
    dist_xy = math.hypot(dx, dy)
    if not math.isfinite(dist_xy) or dist_xy < 1e-5:
        return {
            "approx_dir": "at-base",
            "spin_to_view_deg": 0.0,
            "relative_bearing_deg": 0.0,
            "target_yaw_deg": _round_float(robot_yaw_deg, 1),
            "bearing_world_deg": _round_float(robot_yaw_deg, 1),
            "robot_xy_distance_m": _round_float(dist_xy, 3),
        }
    bearing_world = math.degrees(math.atan2(dy, dx))
    spin = _norm_angle_deg(bearing_world - float(robot_yaw_deg))
    target_yaw = _norm_angle_deg(float(robot_yaw_deg) + float(spin or 0.0))
    return {
        "approx_dir": _direction_from_spin_deg(spin),
        "spin_to_view_deg": _round_float(spin, 1),
        "relative_bearing_deg": _round_float(spin, 1),
        "target_yaw_deg": _round_float(target_yaw, 1),
        "bearing_world_deg": _round_float(bearing_world, 1),
        "robot_xy_distance_m": _round_float(dist_xy, 3),
    }


