def format_memory(mem: Dict[str, Any]) -> str:
    if isinstance(mem, dict) and "bddl_completion" in mem:
        return format_task_goals_only_memory(mem)
    if not mem or not mem.get("ok"):
        return "(memory unavailable)"
    head = mem.get("head_camera") or {}
    summary = mem.get("summary") or {}
    coord_range = head.get("coordinate_range") or {}
    u_range = coord_range.get("u") or [0, _QWEN_UV_MAX]
    v_range = coord_range.get("v") or [0, _QWEN_UV_MAX]
    coord_header = (
        "uv coordinate system: Qwen3-VL relative image coords; "
        "top-left=(0,0), bottom-right=(1000,1000)"
    )
    tool_coordinate_rule = (
        "tool coordinates: pass MEMORY u/v directly to every point-tool u/v; "
        "do not scale by image width or height"
    )
    instruction = str(mem.get("task_instruction") or _task_instruction(str(mem.get("task") or ""))).strip()
    lines = [
        f"Task instruction: {instruction}",
        "Task-related objects in head camera:",
        coord_header,
        f"uv nominal range: u={u_range[0]}..{u_range[1]}, v={v_range[0]}..{v_range[1]}; visible UVD is only emitted for non-clipped clickable points",
        tool_coordinate_rule,
        "visible object uvd is a visibility/centering/measurement candidate; clipped/offscreen centers are listed as not visible with a spin hint; for grasp planning, click a real target surface point in the current image, not necessarily the MEMORY center point",
        (
            "format: visible object: (u, v, depth_m) visibility point; hidden object: approx_dir + "
            "spin_to_view_deg + pitch_to_view_deg; depth_m = head camera forward z-depth (-z_cam); "
            "spin positive = turn left / counterclockwise; pitch positive = look up, negative = look down"
        ),
        (
            f"visible={summary.get('visible', 0)}/{summary.get('objects', 0)} "
            f"depth_source={head.get('depth_source', 'none')} "
            f"image={head.get('image_width', 0)}x{head.get('image_height', 0)}"
        ),
        "",
    ]
    objects = mem.get("objects") or {}
    details = mem.get("details") or {}
    for key in sorted(objects.keys()):
        val = objects.get(key)
        det = details.get(key) or {}
        label = key
        cat = det.get("category")
        if cat:
            label = f"{key} [{cat}]"
        if val is None:
            lines.append(f"- {label}: not visible; approx_dir=unknown, spin_to_view=unknown, pitch_to_view=unknown")
        elif val.get("visible") is False or val.get("uv") is None:
            spin = val.get("spin_to_view_deg", det.get("spin_to_view_deg"))
            if isinstance(spin, (int, float)) and math.isfinite(float(spin)):
                spin_s = f"{float(spin):+.1f}deg"
            else:
                spin_s = "unknown"
            pitch = val.get("pitch_to_view_deg", det.get("pitch_to_view_deg"))
            if isinstance(pitch, (int, float)) and math.isfinite(float(pitch)):
                pitch_s = f"{float(pitch):+.1f}deg"
            else:
                pitch_s = "unknown"
            direction = str(val.get("approx_dir") or det.get("approx_dir") or "unknown")
            xy_dist = val.get("robot_xy_distance_m", det.get("robot_xy_distance_m"))
            if isinstance(xy_dist, (int, float)) and math.isfinite(float(xy_dist)):
                dist_s = f"{float(xy_dist):.3f}m"
            else:
                dist_s = "?m"
            reason = str(val.get("reason") or det.get("reason") or "not_visible")
            lines.append(
                f"- {label}: not visible; approx_dir={direction}, "
                f"spin_to_view={spin_s}, pitch_to_view={pitch_s}, "
                f"xy_distance={dist_s}, reason={reason}"
            )
        else:
            uv = val.get("uv")
            if isinstance(uv, list) and len(uv) >= 2:
                u, v = uv[:2]
            else:
                u, v = val.get("u"), val.get("v")
            depth = val.get("depth")
            if isinstance(depth, (int, float)) and math.isfinite(float(depth)):
                depth_s = f"{float(depth):.3f}m"
            else:
                depth_s = "?"
            lines.append(f"- {label}: (u={u}, v={v}, depth={depth_s})")
    if not objects:
        lines.append("- no task-related objects")
    places = mem.get("marked_places") or []
    if places:
        lines.append("")
        lines.append("已标记地点（mark_on_map；spin 正=左转，可直接给 adjust_chassis）:")
        for line in places:
            lines.append(f"- {line}")
    return "\n".join(lines)


def _joint_unit(rec: Dict[str, Any], units: Dict[str, str]) -> str:
    jt = str(rec.get("type") or "")
    return str(units.get(jt) or "unit")


def _fmt_num(v: Any, ndigits: int = 4) -> str:
    try:
        f = float(v)
    except Exception:
        return "none"
    if not math.isfinite(f):
        return "none"
    return f"{f:.{ndigits}f}"


def _fmt_limit(limit: Any) -> str:
    if not isinstance(limit, dict):
        return "none"
    lo = limit.get("lower")
    hi = limit.get("upper")
    if lo is None and hi is None:
        return "continuous"
    return f"[{_fmt_num(lo, 3)},{_fmt_num(hi, 3)}]"


def _format_joint_record(rec: Dict[str, Any], units: Dict[str, str]) -> str:
    name = str(rec.get("joint") or "?")
    parent = str(rec.get("parent") or "?")
    child = str(rec.get("child") or "?")
    jt = str(rec.get("type") or "?")
    axis = rec.get("axis")
    axis_s = "?"
    if isinstance(axis, (list, tuple)) and len(axis) >= 3:
        axis_s = ",".join(_fmt_num(x, 0) for x in axis[:3])
    unit = _joint_unit(rec, units)
    q = rec.get("qpos")
    q_s = "none" if q is None else f"{_fmt_num(q, 4)} {unit}"
    return (
        f"  - {name} ({parent}->{child}, {jt}, axis={axis_s}, "
        f"limit={_fmt_limit(rec.get('limit'))}): {q_s}"
    )


def _format_robot_joint_observation(robot_joints: Dict[str, Any]) -> List[str]:
    if not robot_joints:
        return ["- unavailable"]
    units = robot_joints.get("units") or {}
    lines = [
        (
            f"source={robot_joints.get('source', 'unknown')} "
            f"urdf={robot_joints.get('urdf', '?')}"
        ),
        (
            f"observed={robot_joints.get('observed_count', 0)}/"
            f"{robot_joints.get('expected_count', 0)} "
            f"runtime_joints={robot_joints.get('runtime_joint_count', 0)} "
            f"units: revolute/continuous/virtual_revolute=rad, "
            f"prismatic/virtual_prismatic=m"
        ),
    ]
    groups = robot_joints.get("groups") or {}
    for group_name in ("base_pose", "trunk", "left_arm", "left_gripper", "right_arm", "right_gripper"):
        joints = list(groups.get(group_name) or [])
        if not joints:
            continue
        qvals = [
            "none" if rec.get("qpos") is None else _fmt_num(rec.get("qpos"), 4)
            for rec in joints
        ]
        lines.append(f"{group_name}: q=[{', '.join(qvals)}]")
        for rec in joints:
            lines.append(_format_joint_record(rec, units))
    fixed = list(robot_joints.get("fixed_relations") or [])
    if fixed:
        rel = []
        for rec in fixed:
            rel.append(
                f"{rec.get('joint')}({rec.get('parent')}->{rec.get('child')})"
            )
        lines.append("fixed link relations: " + "; ".join(rel))
    wheel_rel = list(robot_joints.get("urdf_wheel_relations") or [])
    if wheel_rel:
        rel = []
        for rec in wheel_rel:
            rel.append(
                f"{rec.get('joint')}({rec.get('parent')}->{rec.get('child')}, "
                f"{rec.get('type')}, axis={','.join(_fmt_num(x, 0) for x in (rec.get('axis') or [0, 0, 0])[:3])})"
            )
        lines.append("URDF physical wheel/steer relations (not runtime qpos names): " + "; ".join(rel))
    return lines
