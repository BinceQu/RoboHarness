@lru_cache(maxsize=1)
def _challenge_task_instructions() -> Dict[str, str]:
    """Return BEHAVIOR Challenge task_name -> natural-language task instruction."""
    out: Dict[str, str] = {}
    try:
        from .challenge_tasks import BEHAVIOR_CHALLENGE_2026_TASKS
    except Exception:
        BEHAVIOR_CHALLENGE_2026_TASKS = ()

    for task in BEHAVIOR_CHALLENGE_2026_TASKS:
        name = str(task.get("name") or "").strip()
        instruction = str(task.get("instruction") or "").strip()
        if name and instruction:
            out[name] = instruction
    if out:
        return out

    # Legacy fallback for checkouts that only have the 2025 sampled episodes.
    try:
        from .challenge_tasks import BEHAVIOR_CHALLENGE_2025_TASKS
    except Exception:
        return {}
    id_to_name = {
        int(task["id"]): str(task["name"])
        for task in BEHAVIOR_CHALLENGE_2025_TASKS
        if "id" in task and "name" in task
    }
    episodes_path = (
        _repo_root()
        / "datasets"
        / "2025-challenge-task-instances"
        / "metadata"
        / "episodes.jsonl"
    )
    try:
        with episodes_path.open("r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                rec = json.loads(line)
                task_id = int(rec.get("episode_index", 0)) // 10000
                task_name = id_to_name.get(task_id)
                tasks = rec.get("tasks") or []
                instruction = " ".join(str(x).strip() for x in tasks if str(x).strip())
                if task_name and instruction and task_name not in out:
                    out[task_name] = " ".join(instruction.split())
                if len(out) >= len(id_to_name):
                    break
    except Exception:
        return {}
    return out


def _task_instruction(task_name: str) -> str:
    task_name = str(task_name or "").strip()
    if not task_name:
        return "unknown task"
    return _challenge_task_instructions().get(task_name) or task_name.replace("_", " ")


