def _joint_attr_float(joint_el: ET.Element, tag: str, attr: str) -> Optional[float]:
    child = joint_el.find(tag)
    if child is None:
        return None
    val = child.get(attr)
    if val is None or val == "":
        return None
    try:
        return float(val)
    except Exception:
        return None


def _joint_child_attr(joint_el: ET.Element, tag: str, attr: str, default: str = "") -> str:
    child = joint_el.find(tag)
    if child is None:
        return default
    return str(child.get(attr) or default)


@lru_cache(maxsize=4)
def _r1pro_urdf_joint_map() -> Dict[str, Dict[str, Any]]:
    """Parse the R1Pro URDF once so Memory can explain joint/link relations."""
    path = _repo_root() / _R1PRO_URDF_REL
    out: Dict[str, Dict[str, Any]] = {}
    try:
        root = ET.parse(path).getroot()
    except Exception:
        return out
    for joint_el in root.findall("joint"):
        name = str(joint_el.get("name") or "")
        if not name:
            continue
        parent = _joint_child_attr(joint_el, "parent", "link")
        child = _joint_child_attr(joint_el, "child", "link")
        axis_s = _joint_child_attr(joint_el, "axis", "xyz", "0 0 0")
        axis = []
        for part in axis_s.split():
            try:
                axis.append(float(part))
            except Exception:
                axis.append(0.0)
        while len(axis) < 3:
            axis.append(0.0)
        out[name] = {
            "joint": name,
            "type": str(joint_el.get("type") or ""),
            "parent": parent,
            "child": child,
            "axis": [round(float(x), 6) for x in axis[:3]],
            "limit": {
                "lower": _joint_attr_float(joint_el, "limit", "lower"),
                "upper": _joint_attr_float(joint_el, "limit", "upper"),
            },
        }
    return out


def _joint_qpos_by_name(robot: Any) -> Tuple[Dict[str, float], List[str]]:
    if robot is None:
        return {}, []
    try:
        names = [str(n) for n in list(getattr(robot, "joints", {}).keys())]
        qpos = _to_np(robot.get_joint_positions()).reshape(-1)
    except Exception:
        return {}, []
    by_name: Dict[str, float] = {}
    for idx, name in enumerate(names):
        if idx >= qpos.size:
            break
        val = _round_float(qpos[idx], 5)
        if val is not None:
            by_name[name] = val
    return by_name, names


def _joint_record(joint_name: str, q_by_name: Dict[str, float], urdf: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    info = dict(
        urdf.get(joint_name)
        or _ROBOT_RUNTIME_BASE_JOINT_INFO.get(joint_name)
        or {"joint": joint_name}
    )
    q = q_by_name.get(joint_name)
    info["qpos"] = q
    info["observed"] = q is not None
    return info


def _build_robot_joint_observation(world) -> Dict[str, Any]:
    """Current qpos grouped by the R1Pro URDF control chains."""
    robot = getattr(world, "robot", None)
    urdf = _r1pro_urdf_joint_map()
    q_by_name, runtime_names = _joint_qpos_by_name(robot)
    groups: Dict[str, List[Dict[str, Any]]] = {}
    for group_name, joint_names in _ROBOT_RUNTIME_JOINT_GROUPS:
        groups[group_name] = [
            _joint_record(jn, q_by_name, urdf)
            for jn in joint_names
        ]
    fixed_relations = [
        _joint_record(jn, q_by_name, urdf)
        for jn in _ROBOT_FIXED_RELATION_JOINTS
        if jn in urdf
    ]
    urdf_wheel_relations = [
        _joint_record(jn, q_by_name, urdf)
        for jn in _ROBOT_URDF_WHEEL_RELATION_JOINTS
        if jn in urdf
    ]
    observed = sum(
        1
        for joints in groups.values()
        for rec in joints
        if rec.get("observed")
    )
    expected = sum(len(joints) for joints in groups.values())
    return {
        "ok": robot is not None and bool(q_by_name),
        "robot_type": type(robot).__name__ if robot is not None else None,
        "source": "runtime robot.get_joint_positions() matched by joint name; relations from R1Pro URDF",
        "urdf": str(_R1PRO_URDF_REL),
        "units": {
            "revolute": "rad",
            "continuous": "rad",
            "prismatic": "m",
            "virtual_revolute": "rad",
            "virtual_prismatic": "m",
        },
        "observed_count": observed,
        "expected_count": expected,
        "runtime_joint_count": len(runtime_names),
        "runtime_joint_names": runtime_names,
        "groups": groups,
        "fixed_relations": fixed_relations,
        "urdf_wheel_relations": urdf_wheel_relations,
    }


def _project_point(
    cam_pos: np.ndarray,
    cam_quat: np.ndarray,
    p_world: np.ndarray,
    w: int,
    h: int,
    fl: float,
    ha: float,
) -> Optional[Dict[str, float]]:
    """Project a world point into the USD camera image. Camera looks along -Z."""
    R = _quat_to_mat(cam_quat)
    p_cam = R.T @ (np.asarray(p_world, dtype=np.float64).reshape(3) - cam_pos)
    if float(p_cam[2]) >= -1e-6:
        return None
    fx = float(fl) / float(ha) * float(w)
    fy = fx
    u = fx * float(p_cam[0]) / (-float(p_cam[2])) + float(w) / 2.0
    v = float(h) / 2.0 - fy * float(p_cam[1]) / (-float(p_cam[2]))
    return {"u": u, "v": v, "camera_depth_m": -float(p_cam[2])}


def _aabb_points(lo: Optional[np.ndarray], hi: Optional[np.ndarray], center: np.ndarray) -> List[np.ndarray]:
    if lo is None or hi is None:
        return [center]
    lo = np.asarray(lo, dtype=np.float64).reshape(3)
    hi = np.asarray(hi, dtype=np.float64).reshape(3)
    c = (lo + hi) * 0.5
    pts: List[np.ndarray] = [c]
    for x in (lo[0], hi[0]):
        for y in (lo[1], hi[1]):
            for z in (lo[2], hi[2]):
                pts.append(np.array([x, y, z], dtype=np.float64))
    pts.extend([
        np.array([lo[0], c[1], c[2]], dtype=np.float64),
        np.array([hi[0], c[1], c[2]], dtype=np.float64),
        np.array([c[0], lo[1], c[2]], dtype=np.float64),
        np.array([c[0], hi[1], c[2]], dtype=np.float64),
        np.array([c[0], c[1], lo[2]], dtype=np.float64),
        np.array([c[0], c[1], hi[2]], dtype=np.float64),
    ])
    return pts


def _finite_patch_depth(depth: np.ndarray, u: int, v: int, radius: int = 2) -> Optional[float]:
    h, w = depth.shape[:2]
    u0, u1 = max(0, int(u) - radius), min(w, int(u) + radius + 1)
    v0, v1 = max(0, int(v) - radius), min(h, int(v) + radius + 1)
    patch = np.asarray(depth[v0:v1, u0:u1], dtype=np.float64).reshape(-1)
    patch = patch[np.isfinite(patch) & (patch > 0.01) & (patch < 80.0)]
    if patch.size == 0:
        return None
    return float(np.median(patch))


def _depth_visible(
    depth: Optional[np.ndarray],
    proj: Dict[str, float],
    radius_m: float,
) -> Tuple[bool, Optional[float], str]:
    if depth is None:
        return True, None, "projection_only"
    u = int(round(float(proj["u"])))
    v = int(round(float(proj["v"])))
    observed = _finite_patch_depth(depth, u, v)
    if observed is None:
        return False, None, "no_depth_at_pixel"
    expected = float(proj["camera_depth_m"])
    front_tol = max(0.08, float(radius_m) + 0.06)
    back_tol = 0.12
    if expected - front_tol <= observed <= expected + back_tol:
        return True, observed, "depth_visible"
    return False, observed, "depth_occluded"


def _uv_margin_px(w: int, h: int) -> int:
    if w <= 0 or h <= 0:
        return 0
    return int(round(max(_UV_EXTEND_MIN_PX, min(_UV_EXTEND_MAX_PX, max(w, h) * _UV_EXTEND_FRAC))))


def _pixel_to_qwen_uv(u_px: float, v_px: float, w: int, h: int) -> Tuple[int, int]:
    """Convert image pixel coordinates to Qwen3-VL's 0..1000 relative coords.

    Raw projected pixel uv may intentionally use an extended image margin for
    internal visibility/heading logic.  The formatted MEMORY shown to the VLM,
    however, must stay in Qwen's nominal 0..1000 coordinate range because the
    model is expected to output those coordinates directly.
    """
    if w <= 1 or h <= 1:
        u = int(round(float(u_px)))
        v = int(round(float(v_px)))
    else:
        u = int(round(float(u_px) / float(w - 1) * float(_QWEN_UV_MAX)))
        v = int(round(float(v_px) / float(h - 1) * float(_QWEN_UV_MAX)))
    u = max(0, min(int(_QWEN_UV_MAX), u))
    v = max(0, min(int(_QWEN_UV_MAX), v))
    return u, v


def _qwen_uv_clickable(u: int, v: int) -> bool:
    """Whether a model-facing point is safe to present as clickable UVD.

    MEMORY may use extended projections internally to compute turn hints for
    partially/off-screen objects.  Those edge-clamped points are bad action
    targets, so do not expose them as visible object UVD.
    """
    try:
        uu = int(u)
        vv = int(v)
    except Exception:
        return False
    m = int(_QWEN_CLICK_MARGIN)
    return m <= uu <= int(_QWEN_UV_MAX) - m and m <= vv <= int(_QWEN_UV_MAX) - m


def _uv_margin_qwen(w: int, h: int, margin_px: Optional[int] = None) -> int:
    if w <= 1 or h <= 1:
        return 0
    m = _uv_margin_px(w, h) if margin_px is None else int(max(0, margin_px))
    denom = float(max(1, min(w - 1, h - 1)))
    return int(round(float(m) / denom * float(_QWEN_UV_MAX)))


def _uv_in_image(proj: Dict[str, float], w: int, h: int) -> bool:
    return 0 <= float(proj["u"]) < float(w) and 0 <= float(proj["v"]) < float(h)


def _uv_in_extended_range(proj: Dict[str, float], w: int, h: int, margin_px: int) -> bool:
    m = float(max(0, margin_px))
    return -m <= float(proj["u"]) < float(w) + m and -m <= float(proj["v"]) < float(h) + m


def _task_scope_objects(world, tro: Dict[str, Any]) -> Iterable[Tuple[str, Any]]:
    scope = {}
    try:
        scope = getattr(world.env.task, "object_scope", None) or {}
    except Exception:
        scope = {}
    keys = list(tro.keys()) if tro else list(scope.keys())
    seen = set()
    for key in keys:
        if key in seen:
            continue
        seen.add(key)
        ent = scope.get(key)
        obj = getattr(ent, "unwrapped", ent) if ent is not None else None
        yield str(key), obj


def _object_geometry(obj: Any, tro_entry: Dict[str, Any]) -> Tuple[np.ndarray, Optional[np.ndarray], Optional[np.ndarray]]:
    lo = hi = None
    if obj is not None:
        try:
            aabb = obj.aabb
            lo = _to_np(aabb[0]).reshape(3)
            hi = _to_np(aabb[1]).reshape(3)
            return (lo + hi) * 0.5, lo, hi
        except Exception:
            pass
        try:
            pos, _quat = obj.get_position_orientation()
            return _to_np(pos).reshape(3), None, None
        except Exception:
            pass
    pos = np.asarray(tro_entry.get("pos", [0.0, 0.0, 0.0]), dtype=np.float64).reshape(3)
    return pos, None, None


def _object_radius(lo: Optional[np.ndarray], hi: Optional[np.ndarray]) -> float:
    if lo is None or hi is None:
        return 0.10
    return max(0.04, float(np.linalg.norm(np.asarray(hi) - np.asarray(lo))) * 0.5)


def _select_head_projection(
    *,
    head: Optional[Any],
    cam: Dict[str, Any],
    depth: Optional[np.ndarray],
    center: np.ndarray,
    lo: Optional[np.ndarray],
    hi: Optional[np.ndarray],
    radius_m: float,
    use_depth: bool = True,
) -> Tuple[Optional[Dict[str, float]], str, Optional[float]]:
    reason = "no_head_camera" if head is None else "out_of_view"
    chosen = None
    observed_depth = None
    if head is None:
        return None, reason, None

    candidates = []
    w = int(cam["image_width"])
    h = int(cam["image_height"])
    margin_px = _uv_margin_px(w, h)
    for pt in _aabb_points(lo, hi, center):
        proj = _project_point(
            cam["pos"], cam["quat"], pt, w, h,
            float(cam["focal_length"]), float(cam["horizontal_aperture"]),
        )
        if proj is None:
            continue
        if not _uv_in_extended_range(proj, w, h, margin_px):
            continue
        proj = dict(proj)
        proj["in_image"] = _uv_in_image(proj, w, h)
        proj["uv_margin_px"] = margin_px
        if use_depth and bool(proj["in_image"]):
            ok, obs_d, why = _depth_visible(depth, proj, radius_m)
        elif use_depth:
            ok, obs_d, why = True, None, "projection_extended"
        else:
            why = "projection_visible" if bool(proj["in_image"]) else "projection_extended"
            ok, obs_d = True, None
        candidates.append((ok, obs_d, why, proj))
        if ok:
            chosen = proj
            observed_depth = obs_d
            reason = why
            break
    if chosen is None and candidates:
        reason = candidates[0][2]
    return chosen, reason, observed_depth


def _gripper_memory_points(world) -> Iterable[Tuple[str, np.ndarray, Dict[str, Any]]]:
    robot = getattr(world, "robot", None)
    arms = list(getattr(robot, "arm_names", []) or ["left", "right"])
    arms = [str(a).lower() for a in arms if str(a).lower() in ("left", "right")]
    if not arms:
        arms = ["left", "right"]
    for arm in arms:
        key = f"{arm}_gripper"
        try:
            pose = world.eef_pose(arm=arm)
            eef_pos = np.asarray(pose.get("pos"), dtype=np.float64).reshape(3)
            eef_quat = np.asarray(pose.get("quat"), dtype=np.float64).reshape(4)
            if not (np.all(np.isfinite(eef_pos)) and np.all(np.isfinite(eef_quat))):
                raise ValueError("non-finite eef pose")
            center = eef_pos
            yield key, center, {
                "arm": arm,
                "category": "gripper",
                "scene_name": key,
                "point_kind": "eef_pose_origin",
                "eef_pos": eef_pos,
                "eef_quat": eef_quat,
            }
        except Exception as e:
            yield key, np.zeros(3, dtype=np.float64), {
                "arm": arm,
                "category": "gripper",
                "scene_name": key,
                "point_kind": "eef_pose_origin",
                "error": str(e),
            }


def _read_head_depth(head) -> Tuple[Optional[np.ndarray], str]:
    have = list(getattr(head, "modalities", []))
    if "depth_linear" not in have:
        try:
            head.add_modality("depth_linear")
        except Exception:
            return None, "no_depth_modality"
        return None, "depth_requested"
    try:
        obs, _info = head.get_obs()
    except Exception:
        return None, "depth_unavailable"
    depth = obs.get("depth_linear")
    if depth is None:
        return None, "depth_unavailable"
    depth = _to_np_preserve_dtype(depth)
    if depth.ndim == 3:
        depth = depth[..., 0]
    # Keep the sensor dtype here. Converting a 720x720 depth frame to float64
    # allocates about 4 MiB on every periodic refresh; only the tiny sampled
    # patch needs float64 precision in _finite_patch_depth().
    return np.asarray(depth), "depth_linear"


def _head_camera(world) -> Tuple[Optional[Any], Dict[str, Any]]:
    try:
        from behavior_interface.head_capture import get_head_sensor, head_intrinsics_tuple

        head = get_head_sensor(world)
        if head is None:
            return None, {"reason": "no_head_camera"}
        pos, quat = head.get_position_orientation()
        fl, ha, w, h = head_intrinsics_tuple(head)
        return head, {
            "pos": _to_np(pos).reshape(3),
            "quat": _to_np(quat).reshape(4),
            "focal_length": float(fl),
            "horizontal_aperture": float(ha),
            "image_width": int(w),
            "image_height": int(h),
        }
    except Exception as e:
        return None, {"reason": str(e)}


def build_memory(
    world,
    *,
    task_name: str = "",
    robot_pose: Optional[Dict[str, Any]] = None,
    tro: Optional[Dict[str, Any]] = None,
    tick: Optional[int] = None,
    head: Optional[Any] = None,
    head_camera: Optional[Dict[str, Any]] = None,
    depth_linear: Optional[np.ndarray] = None,
    image_id: Optional[str] = None,
) -> Dict[str, Any]:
    """Build web memory for task-relevant objects.

    ``objects`` maps each task object to a visible uv-depth record, or to an
    invisible heading record with ``spin_to_view_deg``.  Positive spin matches
    ``move_in_robot_coord(spin=...)``: turn left / counterclockwise.
    """
    tro = dict(tro or {})
    robot_pose, robot_pose_source = _numeric_robot_pose(world, dict(robot_pose or {}))
    robot_pos = np.array([
        float(robot_pose.get("x", 0.0)),
        float(robot_pose.get("y", 0.0)),
        float(robot_pose.get("z", 0.0)),
    ], dtype=np.float64)
    robot_yaw_deg = float(robot_pose.get("yaw_deg", 0.0))
    robot_joints = _build_robot_joint_observation(world)
    depth = None
    depth_source = "none"
    if head_camera is not None:
        cam = dict(head_camera)
        if "pos" in cam:
            cam["pos"] = _to_np(cam["pos"]).reshape(3)
        if "quat" in cam:
            cam["quat"] = _to_np(cam["quat"]).reshape(4)
        if depth_linear is not None:
            depth = _to_np_preserve_dtype(depth_linear)
            if depth.ndim == 3:
                depth = depth[..., 0]
            depth_source = "capture_depth_linear"
        else:
            depth_source = "capture_no_depth"
        # Do not re-read the sensor when an explicit capture camera is supplied:
        # this keeps MEMORY UVD bound to the exact image/depth/camera pose that
        # was just saved under image_id.
        head = head if head is not None else object()
    else:
        head, cam = _head_camera(world)
        if head is not None:
            depth, depth_source = _read_head_depth(head)

    objects: Dict[str, Dict[str, Any]] = {}
    details: Dict[str, Dict[str, Any]] = {}
    total = visible = 0

    for key, obj in _task_scope_objects(world, tro):
        total += 1
        entry = tro.get(key, {}) if isinstance(tro.get(key), dict) else {}
        center, lo, hi = _object_geometry(obj, entry)
        category = str(getattr(obj, "category", entry.get("category", "")) or "")
        scene_name = str(getattr(obj, "name", entry.get("scene_name", "")) or "")
        radius = _object_radius(lo, hi)
        chosen, reason, observed_depth = _select_head_projection(
            head=head, cam=cam, depth=depth, center=center, lo=lo, hi=hi,
            radius_m=radius, use_depth=True,
        )

        robot_depth = float(np.linalg.norm(center - robot_pos))
        spin_hint = _spin_hint_for_center(center, robot_pos, robot_yaw_deg)
        pitch_hint = _pitch_hint_for_center(center, cam)
        chosen_clickable = False
        qwen_u = qwen_v = None
        u = v = None
        if chosen is not None:
            u = int(round(float(chosen["u"])))
            v = int(round(float(chosen["v"])))
            qwen_u, qwen_v = _pixel_to_qwen_uv(
                u, v,
                int(cam.get("image_width", 0) or 0),
                int(cam.get("image_height", 0) or 0),
            )
            chosen_clickable = bool(chosen.get("in_image")) and _qwen_uv_clickable(qwen_u, qwen_v)
        if chosen is not None and chosen_clickable:
            camera_depth = float(chosen["camera_depth_m"])
            objects[key] = {
                "visible": True,
                "uv": [qwen_u, qwen_v],
                "u": qwen_u,
                "v": qwen_v,
                "coord_system": COORDINATE_SYSTEM,
                "depth": round(camera_depth, 3),
                "depth_kind": "camera_forward_z",
                "clickable": True,
            }
            visible += 1
        else:
            hidden_reason = reason
            if chosen is not None and not chosen_clickable:
                hidden_reason = "projection_clipped_not_clickable"
            objects[key] = _hidden_memory_record(
                center=center,
                robot_pos=robot_pos,
                robot_yaw_deg=robot_yaw_deg,
                robot_distance_m=robot_depth,
                reason=hidden_reason,
                cam=cam,
            )
        details[key] = {
            "visible": bool(chosen is not None and chosen_clickable),
            "clickable": bool(chosen is not None and chosen_clickable),
            "reason": reason,
            "category": category,
            "scene_name": scene_name,
            "center_world": [round(float(x), 4) for x in center.tolist()],
            "robot_distance_m": round(robot_depth, 3),
            "robot_xy_distance_m": spin_hint.get("robot_xy_distance_m"),
            "approx_dir": spin_hint.get("approx_dir"),
            "spin_to_view_deg": spin_hint.get("spin_to_view_deg"),
            "relative_bearing_deg": spin_hint.get("relative_bearing_deg"),
            "target_yaw_deg": spin_hint.get("target_yaw_deg"),
            "bearing_world_deg": spin_hint.get("bearing_world_deg"),
            "pitch_to_view_deg": pitch_hint.get("pitch_to_view_deg"),
            "pitch_to_view_raw_deg": pitch_hint.get("pitch_to_view_raw_deg"),
            "target_pitch_deg": pitch_hint.get("target_pitch_deg"),
            "camera_pitch_deg": pitch_hint.get("camera_pitch_deg"),
            "pitch_hint_reason": pitch_hint.get("pitch_hint_reason"),
            "camera_depth_m": (
                round(float(chosen["camera_depth_m"]), 3) if chosen is not None else None
            ),
            "observed_depth_linear_m": (
                round(float(observed_depth), 3) if observed_depth is not None else None
            ),
        }

    for key, center, meta in _gripper_memory_points(world):
        total += 1
        chosen = None
        observed_depth = None
        reason = meta.get("error") or ("no_head_camera" if head is None else "out_of_view")
        if not meta.get("error"):
            chosen, reason, observed_depth = _select_head_projection(
                head=head, cam=cam, depth=depth, center=center, lo=None, hi=None,
                radius_m=0.08, use_depth=False,
            )

        robot_depth = float(np.linalg.norm(center - robot_pos))
        spin_hint = _spin_hint_for_center(center, robot_pos, robot_yaw_deg)
        pitch_hint = _pitch_hint_for_center(center, cam)
        if chosen is not None:
            u = int(round(float(chosen["u"])))
            v = int(round(float(chosen["v"])))
            qwen_u, qwen_v = _pixel_to_qwen_uv(
                u, v,
                int(cam.get("image_width", 0) or 0),
                int(cam.get("image_height", 0) or 0),
            )
            camera_depth = float(chosen["camera_depth_m"])
            objects[key] = {
                "visible": True,
                "uv": [qwen_u, qwen_v],
                "u": qwen_u,
                "v": qwen_v,
                "coord_system": COORDINATE_SYSTEM,
                "depth": round(camera_depth, 3),
                "depth_kind": "camera_forward_z",
            }
            visible += 1
        else:
            objects[key] = _hidden_memory_record(
                center=center,
                robot_pos=robot_pos,
                robot_yaw_deg=robot_yaw_deg,
                robot_distance_m=robot_depth,
                reason=reason,
                cam=cam,
            )

        details[key] = {
            "visible": chosen is not None,
            "reason": reason,
            "category": str(meta.get("category", "gripper")),
            "scene_name": str(meta.get("scene_name", key)),
            "arm": meta.get("arm"),
            "point_kind": meta.get("point_kind"),
            "center_world": [round(float(x), 4) for x in center.tolist()],
            "robot_distance_m": round(robot_depth, 3),
            "robot_xy_distance_m": spin_hint.get("robot_xy_distance_m"),
            "approx_dir": spin_hint.get("approx_dir"),
            "spin_to_view_deg": spin_hint.get("spin_to_view_deg"),
            "relative_bearing_deg": spin_hint.get("relative_bearing_deg"),
            "target_yaw_deg": spin_hint.get("target_yaw_deg"),
            "bearing_world_deg": spin_hint.get("bearing_world_deg"),
            "pitch_to_view_deg": pitch_hint.get("pitch_to_view_deg"),
            "pitch_to_view_raw_deg": pitch_hint.get("pitch_to_view_raw_deg"),
            "target_pitch_deg": pitch_hint.get("target_pitch_deg"),
            "camera_pitch_deg": pitch_hint.get("camera_pitch_deg"),
            "pitch_hint_reason": pitch_hint.get("pitch_hint_reason"),
            "camera_depth_m": (
                round(float(chosen["camera_depth_m"]), 3) if chosen is not None else None
            ),
            "observed_depth_linear_m": (
                round(float(observed_depth), 3) if observed_depth is not None else None
            ),
        }

    return {
        "ok": True,
        "task": task_name,
        "task_instruction": _task_instruction(task_name),
        "updated_ts": time.time(),
        "tick": tick,
        "marked_places": _marked_places_lines(),
        "robot_pose": {
            "x": round(float(robot_pose.get("x", 0.0)), 4),
            "y": round(float(robot_pose.get("y", 0.0)), 4),
            "z": round(float(robot_pose.get("z", 0.0)), 4),
            "yaw_deg": round(float(robot_yaw_deg), 2),
            "source": robot_pose_source,
        },
        "robot_joints": robot_joints,
        "head_camera": {
            "ok": head is not None,
            "image_id": str(image_id or "") or None,
            "image_width": int(cam.get("image_width", 0) or 0),
            "image_height": int(cam.get("image_height", 0) or 0),
            "depth_source": depth_source,
            "binding": "capture_image" if image_id else "server_cache",
            "note": (
                "depth is head-camera forward z-depth in meters; every public uv "
                "uses Qwen3-VL relative coordinates"
            ),
            "coordinate_system": COORDINATE_SYSTEM,
            "coordinate_range": {
                "u": [0, _QWEN_UV_MAX],
                "v": [0, _QWEN_UV_MAX],
                "note": "pass MEMORY u/v directly to every public point-tool u/v",
            },
        },
        "summary": {
            "objects": total,
            "visible": visible,
            "hidden": max(0, total - visible),
            "depth_source": depth_source,
        },
        "objects": objects,
        "details": details,
    }


